#!/usr/bin/env python3
"""Packs C test projects built for Android into a bundle that runs on a device with adb (XBA-19).

    bundle_tests.py --build /work/tests --src /src --out /out/xba-device-tests

--build holds one CMake build directory per project (tests/<name> configured with the NDK toolchain). For every test
ctest knows there (ctest --show-only=json-v1), the bundle gets its executable and every file its command line or
environment points to, with paths rewritten relative to the bundle, plus libSDL2.so. run.sh (generated, POSIX sh,
fine with Android's toybox) runs them in order and writes report.md. tools/android/run_tests.sh drives it over adb.
"""
import argparse
import json
import os
import shlex
import shutil
import subprocess
import sys


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--build", required=True)
    ap.add_argument("--src", required=True)
    ap.add_argument("--out", required=True)
    ap.add_argument("--timeout", type=int, default=300)
    a = ap.parse_args()
    build, src, out = (os.path.abspath(p) for p in (a.build, a.src, a.out))
    shutil.rmtree(out, ignore_errors=True)
    os.makedirs(os.path.join(out, "lib"))

    def place(path, proj, proj_dir):
        """Bundle-relative spelling of `path` (copying the file in); None if it is not ours."""
        for prefix, dest in ((proj_dir, os.path.join("build", proj)), (src, "src")):
            if path == prefix or path.startswith(prefix + "/"):
                rel = os.path.join(dest, os.path.relpath(path, prefix))
                if os.path.isfile(path):
                    target = os.path.join(out, rel)
                    os.makedirs(os.path.dirname(target), exist_ok=True)
                    shutil.copy2(path, target)
                return "$B/" + rel
        return None

    def rewrite(text, proj, proj_dir):
        """Rewrites every token of `text` that is a path under the build or source dir."""
        if os.path.isabs(text):
            placed = place(text, proj, proj_dir)
            if placed:
                return placed
        if "=" in text:                       # KEY=/abs/path in ENVIRONMENT
            k, v = text.split("=", 1)
            if os.path.isabs(v):
                placed = place(v, proj, proj_dir)
                if placed:
                    return k + "=" + placed
        return text

    lines = []
    count = 0
    for proj in sorted(os.listdir(build)):
        proj_dir = os.path.join(build, proj)
        if not os.path.isfile(os.path.join(proj_dir, "CTestTestfile.cmake")):
            continue
        r = subprocess.run(["ctest", "--test-dir", proj_dir, "--show-only=json-v1"],
                           capture_output=True, text=True)
        if r.returncode != 0:
            print(f"{proj}: ctest --show-only failed, skipped", file=sys.stderr)
            continue
        for t in json.loads(r.stdout).get("tests", []):
            cmd = t.get("command")
            if not cmd:
                continue                       # not built
            props = {p["name"]: p["value"] for p in t.get("properties", [])}
            wd = rewrite(props.get("WORKING_DIRECTORY", proj_dir), proj, proj_dir)
            env = [rewrite(e, proj, proj_dir) for e in props.get("ENVIRONMENT", [])]
            argv = [rewrite(c, proj, proj_dir) for c in cmd]
            skip = str(props.get("SKIP_RETURN_CODE", ""))
            will_fail = "1" if props.get("WILL_FAIL") else "0"

            def q(s):
                # "$B/..." must expand on the device: double quotes, everything else single-quoted.
                if s.startswith("$B/") or "=$B/" in s:
                    return '"' + s.replace('"', '\\"') + '"'
                return shlex.quote(s)
            lines.append("run_test %s %s %s %s %s -- %s" % (
                shlex.quote(proj), shlex.quote(t["name"]), shlex.quote(skip or "-"), will_fail, q(wd),
                " ".join(q(x) for x in env + argv)))
            count += 1

    for root, _, files in os.walk(build):     # SDL2 as a shared library, for the tests that link it
        if "libSDL2.so" in files:
            shutil.copy2(os.path.join(root, "libSDL2.so"), os.path.join(out, "lib"))
            break

    with open(os.path.join(out, "run.sh"), "w") as f:
        f.write(RUN_SH_HEAD.replace("@TIMEOUT@", str(a.timeout)))
        f.write("\n".join(lines) + "\n")
        f.write(RUN_SH_TAIL)
    os.chmod(os.path.join(out, "run.sh"), 0o755)
    for root, _, files in os.walk(os.path.join(out, "build")):
        for n in files:
            p = os.path.join(root, n)
            if os.access(p, os.X_OK) or n.endswith("_test"):
                os.chmod(p, 0o755)
    print(f"{count} tests bundled in {out}")


RUN_SH_HEAD = r'''#!/system/bin/sh
# Runs the toolkit's C tests on an Android device (generated by tools/android/bundle_tests.py, XBA-19).
#   sh run.sh [name-filter]      e.g. sh run.sh memory
# Writes report.md (a pass / skip / fail table) and logs/<test>.log next to this script.
B=$(cd "$(dirname "$0")" && pwd)
export LD_LIBRARY_PATH="$B/lib${LD_LIBRARY_PATH:+:$LD_LIBRARY_PATH}"
export TMPDIR="$B/tmp" SDL_VIDEODRIVER=dummy SDL_AUDIODRIVER=dummy
mkdir -p "$B/logs" "$B/tmp"
FILTER="${1:-}"
PASS=0 SKIP=0 FAIL=0
REPORT="$B/report.md"
{
  echo "# Device test run"
  echo
  echo "Device: $(getprop ro.product.manufacturer 2>/dev/null) $(getprop ro.product.model 2>/dev/null), Android $(getprop ro.build.version.release 2>/dev/null) (API $(getprop ro.build.version.sdk 2>/dev/null)), kernel $(uname -r)"
  echo "Date: $(date -u '+%Y-%m-%d %H:%M UTC')"
  echo
  echo "| Project | Test | Result | Exit | Seconds |"
  echo "|---|---|---|---|---|"
} > "$REPORT"

run_test() {
  proj=$1 name=$2 skip=$3 willfail=$4 wd=$5
  shift 6                                   # the five fields and "--"
  case "$name" in *"$FILTER"*) ;; *) return ;; esac
  mkdir -p "$wd"
  start=$(date +%s)
  ( cd "$wd" && timeout @TIMEOUT@ env "$@" ) > "$B/logs/$name.log" 2>&1
  rc=$?
  secs=$(( $(date +%s) - start ))
  if [ "$skip" != "-" ] && [ "$rc" = "$skip" ]; then res=skip
  elif [ "$willfail" = 1 ]; then [ "$rc" != 0 ] && res=pass || res=FAIL
  elif [ "$rc" = 0 ]; then res=pass
  elif [ "$rc" = 124 ] || [ "$rc" = 143 ]; then res=FAIL; rc="$rc (timeout)"
  else res=FAIL
  fi
  case $res in pass) PASS=$((PASS+1));; skip) SKIP=$((SKIP+1));; *) FAIL=$((FAIL+1));; esac
  echo "| $proj | $name | $res | $rc | $secs |" >> "$REPORT"
  printf '%-40s %-5s rc=%s\n' "$name" "$res" "$rc"
}

'''

RUN_SH_TAIL = r'''
{ echo; echo "**$PASS pass, $SKIP skip, $FAIL fail.** Logs: logs/<test>.log"; } >> "$REPORT"
echo "$PASS pass, $SKIP skip, $FAIL fail -- $REPORT"
[ "$FAIL" = 0 ]
'''

if __name__ == "__main__":
    main()
