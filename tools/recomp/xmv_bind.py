"""
The XMV binding the lifter generates (XBA-199, docs/runtime/xmv.md).

tools.prepare finds the XDK's XMVDecoder_GetNextFrame (and CloseDecoder) in
the XBE (tools.xmv.find_api) and, when it is sure, hands the addresses to
tools.recomp --xmv-bind FILE. The lifter then emits those bodies as
sub_X_gen (the --exclude-manual wrap mechanism) and writes
recomp_xmv_bind.c into the generated sources: sub_X, reached by every caller
and by the dispatch table, calls the runtime's decoder (xmv_hle_get_next_frame,
xmv_hle_close) or the title's own lifted body: with RECOMP_XMV=native, and for
a movie the runtime would not decode exactly (xmv_hle_route decides per movie;
xmv_hle_native_result watches the title's decoder for a hang). Not a
title layer: every title whose XMV library is found gets it, and nothing of
any one title is in the toolkit.

FILE (written by tools.xmv.find_api.prepare_bind):
    {"get_next_frame": "0x...", "close_decoder": "0x..." (optional), "confidence": 0.9, "xdk": 5849,
     "timestamp": "ms32" | "100ns64", "timestamp_source": "body" | "build" | "default" | "conflict"}

"timestamp" is the layout of GetNextFrame's 4th argument for the title's XDK
build (XBA-316, find_api.timestamp_layout); a file without it (written before
XBA-316) gets "ms32", the layout read in XDK 5849.
"""

import json
import os
import sys

FILE_NAME = "recomp_xmv_bind.c"
# The shape of the generated binding, part of the lift's stamp (find_api.bind_key): a change re-lifts.
# 2: GetNextFrame routed per movie (xmv_hle_route, xmv_hle_native_result: the hand-over, XBA-199).
# 3: the timestamp's layout passed to xmv_hle_get_next_frame_ex (XBA-316).
VERSION = 3
# The runtime's XMV_TIME_* (src/video/xmv_hle.h).
TIME_LAYOUT = {"ms32": (0, "XMV_TIME_MS32: one DWORD, ms"), "100ns64": (1, "XMV_TIME_100NS64: 64-bit, 100 ns")}
WHAT = {"get_next_frame": (0, "XMVDecoder_GetNextFrame"), "close_decoder": (1, "XMVDecoder_CloseDecoder")}


def load(path):
    with open(path, encoding="utf-8") as f:
        plan = json.load(f)
    out = {"confidence": float(plan.get("confidence", 0)), "xdk": plan.get("xdk"),
           "timestamp": plan.get("timestamp") or "ms32"}
    if out["timestamp"] not in TIME_LAYOUT:
        raise ValueError("%s: timestamp %r is not one of %s" % (path, out["timestamp"], ", ".join(TIME_LAYOUT)))
    for k in WHAT:
        v = plan.get(k)
        if v:
            out[k] = int(v, 16) if isinstance(v, str) else int(v)
    if "get_next_frame" not in out:
        raise ValueError("%s: no get_next_frame" % path)
    return out


def select(plan, known, hand_written, log=None):
    """{name: addr} of what to bind: known functions the project does not define by hand."""
    log = log or (lambda m: print(m, file=sys.stderr))
    bound = {}
    for k, (_, api) in WHAT.items():
        addr = plan.get(k)
        if addr is None:
            continue
        if addr not in known:
            log("XMV: %s 0x%08X is not a function the analysis found: not bound" % (api, addr))
            if k == "get_next_frame":
                return {}
            continue
        if addr in hand_written:
            log("XMV: %s 0x%08X is written by hand (--exclude-manual): not bound" % (api, addr))
            if k == "get_next_frame":
                return {}
            continue
        bound[k] = addr
    return bound


def source(bound, plan):
    """recomp_xmv_bind.c for {name: addr}."""
    pct = int(round(plan.get("confidence", 0) * 100))
    lines = [
        "/* Generated by tools.recomp --xmv-bind (XBA-199, docs/runtime/xmv.md): the XDK's XMV API,",
        " * found in this XBE by tools.xmv.find_api (confidence %.2f), bound to the runtime's movie" % (pct / 100.0),
        " * decoder. Not a title layer: generated for every title whose XMV library is found.",
        " * RECOMP_XMV=native runs the title's own decoder (the lifted body, sub_X_gen). */",
        "#define RECOMP_GENERATED_CODE",
        '#include "recomp_funcs.h"',
        "",
        "extern int xmv_hle_bound(int what, uint32_t va, unsigned confidence_pct);",
        "extern uint32_t xmv_hle_get_next_frame_ex(uint32_t decoder_va, uint32_t surface_va,",
        "                                          uint32_t result_va, uint32_t time_va, unsigned time_layout);",
        "extern void xmv_hle_close(uint32_t decoder_va);",
        "extern int xmv_hle_route(uint32_t va, unsigned confidence_pct, uint32_t decoder_va);",
        "extern void xmv_hle_native_result(uint32_t decoder_va, uint32_t result_va);",
        "",
    ]
    layout, layout_what = TIME_LAYOUT[plan.get("timestamp") or "ms32"]
    for k, addr in sorted(bound.items(), key=lambda kv: WHAT[kv[0]][0]):
        what, api = WHAT[k]
        name = "sub_%08X" % addr
        if k == "get_next_frame":
            lines += [
                "void %s(void)    /* %s(decoder, surface, &result, &timestamp) */" % (name, api),
                "{",
                "    uint32_t decoder = MEM32(esp + 4), result = MEM32(esp + 12);",
                "    if (!xmv_hle_route(0x%08Xu, %du, decoder)) {" % (addr, pct),
                "        /* RECOMP_XMV=native, or a movie the runtime hands to the title's own decoder */",
                "        %s_gen();" % name,
                "        xmv_hle_native_result(decoder, result);",
                "        return;",
                "    }",
                "    eax = xmv_hle_get_next_frame_ex(MEM32(esp + 4), MEM32(esp + 8), MEM32(esp + 12), MEM32(esp + 16),",
                "                                    %du);  /* timestamp: %s */" % (layout, layout_what),
                "    esp += 4 + 16;              /* stdcall: ret 0x10 */",
                "}",
                "",
            ]
        else:
            lines += [
                "void %s(void)    /* %s(decoder) */" % (name, api),
                "{",
                "    if (xmv_hle_bound(%d, 0x%08Xu, %du))" % (what, addr, pct),
                "        xmv_hle_close(MEM32(esp + 4));",
                "    %s_gen();                   /* the title's own close still runs */" % name,
                "}",
                "",
            ]
    return "\n".join(lines)


def write(gen_dir, bound, plan):
    path = os.path.join(gen_dir, FILE_NAME)
    with open(path, "w", encoding="utf-8") as f:
        f.write(source(bound, plan))
    return path
