"""
A Win32 PE through the x86 pipeline to a native executable (XBA-233, epic XBA-231).

    python3 -m tools.win32 PROGRAM.exe --work DIR [--cc gcc] [--run [ARGS...]]

1. tools.pe_parser --json      the analysis JSON (sections, entry point, imports)
2. tools.disasm                functions, xrefs, strings
3. tools.func_id               library / game classification
4. tools.abi_analysis          calling conventions
5. tools.recomp --all          the lifted C (DIR/gen)
6. cc                          DIR/gen + the Win32 runtime (src/win32) + a main -> DIR/<name>

The executable takes the .exe as its first argument (the program's own bytes
and data are read at run time, as an Xbox title reads its XBE) and the rest as
the program's command line. A spike: Linux and macOS hosts, console programs.
"""

import argparse
import os
import shutil
import subprocess
import sys

ROOT = os.path.abspath(os.path.join(os.path.dirname(__file__), "..", ".."))
RUNTIME = os.path.join(ROOT, "src", "win32")
RUNTIME_SOURCES = ("win32_runtime.c", "win32_hle.c")

MAIN_C = """/* Generated by tools.win32 (XBA-233): the Win32 runtime runs the program given as argv[1]. */
#include "win32_runtime.h"

int main(int argc, char **argv)
{
    return w32_main(argc, argv);
}
"""


def _run(cmd, log):
    with open(log, "a") as f:
        f.write("$ " + " ".join(cmd) + "\n")
        f.flush()
        r = subprocess.run(cmd, cwd=ROOT, stdout=f, stderr=subprocess.STDOUT)
    if r.returncode:
        raise RuntimeError(f"{' '.join(cmd[:3])} failed (exit {r.returncode}), see {log}")


def lift(exe, work, py=sys.executable):
    """Steps 1-5: the lifted C in WORK/gen. Returns the gen directory."""
    an = os.path.join(work, "analysis")
    gen = os.path.join(work, "gen")
    os.makedirs(an, exist_ok=True)
    log = os.path.join(work, "pipeline.log")
    js = os.path.join(an, os.path.splitext(os.path.basename(exe))[0] + "_analysis.json")
    d, fid, abi = (os.path.join(an, x) for x in ("disasm", "func_id", "abi"))
    _run([py, "-m", "tools.pe_parser", exe, "--json", js], log)
    _run([py, "-m", "tools.disasm", exe, "--analysis-json", js, "-o", d, "--force"], log)
    _run([py, "-m", "tools.func_id", exe, "--functions", os.path.join(d, "functions.json"),
          "--strings", os.path.join(d, "strings.json"), "--xrefs", os.path.join(d, "xrefs.json"), "-o", fid], log)
    _run([py, "-m", "tools.abi_analysis", exe, "--disasm-dir", d, "--func-id-dir", fid, "--output-dir", abi], log)
    if os.path.isdir(gen):
        shutil.rmtree(gen)
    _run([py, "-m", "tools.recomp", exe, "--all", "--split-bytes", "2000000",
          "--game-name", os.path.basename(exe), "--disasm-dir", d, "--func-id-dir", fid, "--abi-dir", abi,
          "--gen-dir", gen, "-o", os.path.join(an, "recomp")], log)
    return gen


def compile_native(gen, work, name, cc="cc", extra=()):
    """Step 6: WORK/NAME from the lifted C, the runtime and a main."""
    main_c = os.path.join(work, "main.c")
    with open(main_c, "w") as f:
        f.write(MAIN_C)
    out = os.path.join(work, name)
    srcs = sorted(os.path.join(gen, f) for f in os.listdir(gen) if f.endswith(".c"))
    srcs += [os.path.join(RUNTIME, f) for f in RUNTIME_SOURCES] + [main_c]
    # -fno-strict-aliasing -fwrapv: guest memory is one byte array read at every width, and x86 arithmetic wraps.
    cmd = [cc, "-O1", "-w", "-fno-strict-aliasing", "-fwrapv", "-I", gen, "-I", RUNTIME, *srcs, "-lm",
           "-o", out, *extra]
    r = subprocess.run(cmd, capture_output=True, text=True)
    if r.returncode:
        raise RuntimeError("compile failed:\n" + r.stdout[-3000:] + r.stderr[-3000:])
    return out


def build(exe, work, cc="cc", extra=()):
    os.makedirs(work, exist_ok=True)
    gen = lift(os.path.abspath(exe), work)
    return compile_native(gen, work, os.path.splitext(os.path.basename(exe))[0], cc, extra)


def main(argv=None):
    ap = argparse.ArgumentParser(prog="python3 -m tools.win32", description=__doc__.split("\n\n")[1])
    ap.add_argument("exe", help="a 32-bit Windows console program (PE32, i386)")
    ap.add_argument("--work", required=True, help="work folder (analysis, lifted C, the native executable)")
    ap.add_argument("--cc", default=os.environ.get("CC", "cc"))
    ap.add_argument("--run", nargs=argparse.REMAINDER, help="run it afterwards, with these arguments")
    a = ap.parse_args(argv)
    try:
        prog = build(a.exe, a.work, a.cc)
    except RuntimeError as e:
        print(f"tools.win32: {e}", file=sys.stderr)
        return 1
    print(f"built {prog}", flush=True)
    if a.run is not None:
        return subprocess.call([prog, os.path.abspath(a.exe), *a.run])
    return 0
