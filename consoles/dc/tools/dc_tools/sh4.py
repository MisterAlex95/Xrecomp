def mnemonic(name: str) -> str:
    if name in _MNEMONIC:
        return _MNEMONIC[name]
    base = name.split("_")[0].lower()
    if name.startswith(("STSL_", "LDSL_", "STCL_", "LDCL_")):
        return base[:3] + ".l"
    if name in ("MUL_L", "DMULU_L", "DMULS_L", "MAC_L", "MOVCA_L"):
        return base + ".l"
    if name in ("MULU_W", "MULS_W", "MAC_W", "SWAP_W", "EXTU_W", "EXTS_W"):
        return base + ".w"
    if name in ("SWAP_B", "EXTU_B", "EXTS_B", "TAS_B"):
        return base + ".b"
    return base


def disasm(pc: int, op: int) -> str:
    """objdump-like text for one instruction (for comments in the generated C and for debugging)."""
    d = decode(op)
    if d is None:
        return ".word 0x%04x" % op
    n, m = (op >> 8) & 15, (op >> 4) & 15
    fmt = d.fmt
    t = branch_target(pc, op, d.name)
    lit = pc_literal(pc, op, d.name)
    if fmt in ("b8", "b12"):
        args = "0x%08x" % t
    else:
        rep = {
            "FVm": "fv%d" % (((op >> 8) & 3) * 4), "FVn": "fv%d" % (((op >> 10) & 3) * 4),
            "DRn": "dr%d" % (((op >> 9) & 7) * 2) if d.name == "FSCA" else "dr%d" % (n & 14),
            "FRm": "fr%d" % m, "FRn": "fr%d" % n, "Rb": "r%d_bank" % (m & 7), "Rm": "r%d" % m, "Rn": "r%d" % n,
            "d4*4": str((op & 15) * 4), "d4*2": str((op & 15) * 2), "d4": str(op & 15),
            "u8*4": str((op & 0xFF) * 4), "u8*2": str((op & 0xFF) * 2), "u8": str(op & 0xFF),
            "s8": str(s8(op)), "pcw": "0x%08x" % lit[0] if lit else "", "pcl": "0x%08x" % lit[0] if lit else "",
        }
        keys = sorted(rep, key=len, reverse=True)
        args = re.sub("|".join(re.escape(k) for k in keys), lambda mt: rep[mt.group(0)], fmt)
    text = mnemonic(d.name)
    return text + ("\t" + args if args else "")


def gen_c_header() -> str:
    lines = [
        "/* sh4_optab.h -- GENERATED by `python3 -m dc_tools.sh4 --gen-c` from consoles/dc/tools/dc_tools/sh4.py",
        " * (XBA-227). Do not edit: change the table in sh4.py and regenerate (test_dc_tools.py checks it is current).",
        " *",
        " * SH4_OPTAB(X): X(NAME, mask, match, flags) in decode order (most specific mask first). */",
        "#ifndef SH4_OPTAB_H",
        "#define SH4_OPTAB_H",
        "",
        "#define SH4F_BRANCH %d" % BRANCH,
        "#define SH4F_DELAY %d" % DELAY,
        "#define SH4F_SYNC %d" % SYNC,
        "#define SH4F_ILLEGAL_IN_SLOT %d" % ILLEGAL_IN_SLOT,
        "#define SH4F_FPU %d" % FPU,
        "",
        "#define SH4_OPTAB(X) \\",
    ]
    for i in _ORDER:
        mask, match, name, _fmt, flags = OPS[i]
        lines.append("    X(%s, 0x%04X, 0x%04X, %d) \\" % (name, mask, match, flags))
    lines.append("    /* end */")
    lines.append("")
    lines.append("#endif")
    return "\n".join(lines) + "\n"


def main(argv: list[str]) -> int:
    if len(argv) == 2 and argv[0] == "--gen-c":
        with open(argv[1], "w", encoding="utf-8") as f:
            f.write(gen_c_header())
        return 0
    if len(argv) == 2 and argv[0] == "--table":
        # One line per opcode: "XXXX NAME" (or "XXXX -"): compared with the C decoder's dc_run --decode-table.
        with open(argv[1], "w", encoding="utf-8") as f:
            for op in range(65536):
                d = decode(op)
                f.write("%04x %s\n" % (op, d.name if d else "-"))
        return 0
    print("usage: python3 -m dc_tools.sh4 --gen-c OUT.h | --table OUT.txt", file=sys.stderr)
    return 2


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
