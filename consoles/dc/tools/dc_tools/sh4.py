# Most specific mask first: the first matching entry wins (FSCHG before FTRV before FSCA before the 0xF0FF group).
_ORDER = sorted(range(len(OPS)), key=lambda i: (-bin(OPS[i][0]).count("1"), i))


@dataclass(frozen=True)
class Op:
    name: str
    flags: int
    fmt: str


_TABLE: list[Op | None] = [None] * 65536


def _build() -> None:
    for op in range(65536):
        for i in _ORDER:
            mask, match, name, fmt, flags = OPS[i]
            if op & mask == match:
                _TABLE[op] = Op(name, flags, fmt)
                break


_build()


def decode(op: int) -> Op | None:
    """The instruction for a 16-bit opcode, or None (illegal / not an SH-4 instruction)."""
    return _TABLE[op & 0xFFFF]


def s8(v: int) -> int:
    v &= 0xFF
    return v - 0x100 if v & 0x80 else v


def s12(v: int) -> int:
    v &= 0xFFF
    return v - 0x1000 if v & 0x800 else v


def branch_target(pc: int, op: int, name: str) -> int | None:
    """Static target of BT / BF / BT_S / BF_S / BRA / BSR, else None."""
    if name in ("BT", "BF", "BT_S", "BF_S"):
        return (pc + 4 + s8(op) * 2) & 0xFFFFFFFF
    if name in ("BRA", "BSR"):
        return (pc + 4 + s12(op) * 2) & 0xFFFFFFFF
    return None


def pc_literal(pc: int, op: int, name: str) -> tuple[int, int] | None:
    """(address, size) a PC-relative load reads (MOV.W / MOV.L @(disp,PC)), MOVA's address with size 0."""
    if name == "MOVW_PC":
        return (pc + 4 + (op & 0xFF) * 2) & 0xFFFFFFFF, 2
    if name == "MOVL_PC":
        return ((pc & ~3) + 4 + (op & 0xFF) * 4) & 0xFFFFFFFF, 4
    if name == "MOVA":
        return ((pc & ~3) + 4 + (op & 0xFF) * 4) & 0xFFFFFFFF, 0
    return None


