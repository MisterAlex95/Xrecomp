"""Lift a Dreamcast program to C (XBA-227, Dreamcast spike).

    python3 -m dc_tools.recomp PROGRAM.elf|1ST_READ.BIN OUTDIR [--discovered FILE] [--no-comments]
                               [--report FILE] [--files N]

Writes OUTDIR/title.h, OUTDIR/rc_NNN.c (the functions, N files) and OUTDIR/table.c (dc_recomp_title_table: the
entries sorted by address, the spans with their FNV-1a, the program's SHA-256). Build them into one shared library
with -I consoles/dc/runtime (add -DDC_RC_COUNT to count native instructions) and give it to dc_run --pack.
--discovered: addresses dc_run --missed reported (hex, one per line, '#' comments): lift again with them until the
interpreter has nothing left to run inside the image. The raw binary must be unscrambled (1ST_READ.BIN as it lies in
RAM at 0x8C010000).
"""

from __future__ import annotations

import argparse
import json
import os
import sys

from . import image
from .lift import Lifter


def fnv1a(data: bytes) -> int:
    h = 2166136261
    for b in data:
        h = ((h ^ b) * 16777619) & 0xFFFFFFFF
    return h


def read_discovered(path: str | None) -> set[int]:
    out: set[int] = set()
    if not path or not os.path.exists(path):
        return out
    with open(path, encoding="utf-8") as f:
        for line in f:
            line = line.split("#", 1)[0].strip()
            if line:
                out.add(int(line, 16))
    return out


def write_pack(lifter: Lifter, outdir: str, comments: bool = True, nfiles: int = 8) -> dict:
    img = lifter.img
    os.makedirs(outdir, exist_ok=True)
    for name in os.listdir(outdir):
        if name.startswith("rc_") and name.endswith(".c"):
            os.remove(os.path.join(outdir, name))
    funcs = [lifter.funcs[a] for a in sorted(lifter.funcs)]
    with open(os.path.join(outdir, "title.h"), "w", encoding="utf-8") as h:
        h.write("/* Generated by dc_tools.recomp (XBA-227) from %s image %s. */\n" % (img.kind, img.sha256))
        h.write("#ifndef DC_TITLE_H\n#define DC_TITLE_H\n#include \"dc_recomp_rt.h\"\n")
        for f in funcs:
            h.write("void %s(sh4_cpu *c);\n" % Lifter.fname(f.entry))
        h.write("#endif\n")
    total_insns = 0
    per = max(1, (len(funcs) + nfiles - 1) // nfiles)
    for k in range(0, len(funcs), per):
        with open(os.path.join(outdir, "rc_%03d.c" % (k // per)), "w", encoding="utf-8") as out:
            out.write("/* Generated by dc_tools.recomp (XBA-227). */\n#include \"title.h\"\n\n")
            for f in funcs[k : k + per]:
                if f.entry in img.symbols and comments:
                    out.write("/* %s */\n" % img.symbols[f.entry].replace("*/", "* /"))
                src, n = lifter.emit_function(f, comments)
                total_insns += n
                out.write(src)
                out.write("\n")
    # The table: every checked label of every function; the function that starts there wins, else the first.
    entries: dict[int, int] = {}
    for f in funcs:
        for t in f.table:
            if t in f.insns and (t not in entries or t == f.entry):
                entries[t] = f.entry
    spans = img.spans()
    with open(os.path.join(outdir, "table.c"), "w", encoding="utf-8") as out:
        out.write("/* Generated by dc_tools.recomp (XBA-227). */\n#include \"title.h\"\n\n")
        out.write("static const dc_recomp_entry entries[] = {\n")
        for a in sorted(entries):
            out.write("    {0x%08xu, %s},\n" % (a, Lifter.fname(entries[a])))
        out.write("};\n\nstatic const dc_recomp_span spans[] = {\n")
        for lo, hi in spans:
            out.write("    {0x%08xu, 0x%08xu, 0x%08xu},\n" % (lo, hi, fnv1a(img.span_bytes(lo, hi))))
        out.write("};\n\nstatic const dc_recomp_table table = {\n")
        out.write("    DC_RECOMP_ABI, %d, entries, %d, spans, \"%s\",\n};\n\n" % (len(entries), len(spans), img.sha256))
        out.write("#if defined(__GNUC__)\n__attribute__((visibility(\"default\")))\n#endif\n")
        out.write("const dc_recomp_table *dc_recomp_title_table(void)\n{\n    return &table;\n}\n")
    fallbacks = sorted({a for f in funcs for a in f.fallbacks})
    return {
        "image": {"kind": img.kind, "sha256": img.sha256, "entry": "0x%08x" % img.entry,
                  "spans": ["0x%08x-0x%08x" % s for s in spans]},
        "functions": len(funcs),
        "entries": len(entries),
        "instructions": total_insns,
        "unique_instructions": len({a for f in funcs for a in f.insns}),
        "jump_tables": sum(len(f.jtables) for f in funcs),
        "interp_fallbacks": len(fallbacks),
        "discovered": len(lifter.discovered),
    }


def main(argv: list[str] | None = None) -> int:
    ap = argparse.ArgumentParser(prog="dc_tools.recomp", description=__doc__.splitlines()[0])
    ap.add_argument("program")
    ap.add_argument("outdir")
    ap.add_argument("--discovered")
    ap.add_argument("--no-comments", action="store_true")
    ap.add_argument("--report")
    ap.add_argument("--files", type=int, default=8)
    a = ap.parse_args(argv)
    img = image.load(a.program)
    lifter = Lifter(img, read_discovered(a.discovered))
    lifter.run()
    rep = write_pack(lifter, a.outdir, not a.no_comments, a.files)
    if a.report:
        with open(a.report, "w", encoding="utf-8") as f:
            json.dump(rep, f, indent=1)
    print("dc_tools.recomp: %d functions, %d table entries, %d instructions (%d unique), %d jump tables, "
          "%d interpreter fallbacks" % (rep["functions"], rep["entries"], rep["instructions"],
                                        rep["unique_instructions"], rep["jump_tables"], rep["interp_fallbacks"]))
    return 0


if __name__ == "__main__":
    sys.exit(main())
