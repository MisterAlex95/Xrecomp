"""`python3 -m ctr_tools.recomp PROG.3dsx OUTDIR [--discovered FILE]`: a 3DS program's ARM11 code to C (XBA-228
spike).

Writes OUTDIR/ctr_rc_AAAAAAAA{a,t}.c (the lifted functions, files cut as gba_tools.recomp cuts them) and
OUTDIR/ctr_rc_table.c (the table, exported as ctr_recomp_title_table), nothing else: compile every .c of OUTDIR with
-I consoles/3ds/runtime -ffp-contract=off into one shared library (contract: consoles/3ds/runtime/ctr_recomp.h). The
table names the code image it was lifted from (address range and FNV-1a after relocation): the core refuses a pack
lifted from another program.
Prints a JSON summary on stdout; --report FILE writes it there too.
"""

import argparse
import glob
import json
import os
import sys

from . import CONSOLE  # noqa: F401  (puts gba_tools and nds_tools on sys.path)
from gba_tools.discover import islands
from gba_tools.lift import hx
from gba_tools.recomp import chunks_of, read_discovered

from .lift import CtrDiscovery, CtrLifter
from .threedsx import Image, ThreeDsxError

HEADER = """/* Generated by ctr_tools.recomp (consoles/3ds/tools) from a 3DS program -- do not edit.
 * 3DSX sha256 %s */
#include "ctr_recomp_rt.h"
"""


def fn_name(f):
    return "ctr_rc_f_%08X_%s" % (f.entry, "t" if f.thumb else "a")


def recompile(image, outdir, discovered=(), comments=True):
    disc = CtrDiscovery(image, discovered)
    funcs = disc.run()
    os.makedirs(outdir, exist_ok=True)
    for old in glob.glob(os.path.join(outdir, "ctr_rc_*.c")):
        os.remove(old)
    fallbacks = 0
    files = []
    for chunk in chunks_of(funcs):
        path = os.path.join(outdir, "ctr_rc_%08X%s.c" % (chunk[0].entry, "t" if chunk[0].thumb else "a"))
        parts = [HEADER % image.sha256]
        for f in chunk:
            lifter = CtrLifter(image, f.thumb, f.addrs)
            text = lifter.function(fn_name(f), (f.entry >> 24) & 15, comments)
            parts.append("\n" + text.replace("(gba_machine *m_)", "(ctr_machine *m_)", 1))
            fallbacks += lifter.fallbacks
        with open(path, "w", encoding="utf-8") as out:
            out.write("".join(parts))
        files.append(path)
    entries = islands(funcs)
    lo, hi, h = image.image_hash()
    tab = [HEADER % image.sha256, "\n"]
    for f in funcs:
        tab.append("RC_FN %s(ctr_machine *m_);\n" % fn_name(f))
    tab.append("\nstatic const ctr_recomp_entry entries[] = {\n")
    for (addr, thumb, f) in entries:
        tab.append("    {%s, %d, %s},\n" % (hx(addr), 1 if thumb else 0, fn_name(f)))
    if not entries:
        tab.append("    {0, 0, 0},\n")
    tab.append("};\n\nstatic const ctr_recomp_table table = {CTR_RECOMP_ABI, %du, entries, %s, %s, %s, \"%s\"};\n\n"
               % (len(entries), hx(lo), hx(hi), hx(h), image.sha256))
    tab.append("RC_EXPORT const ctr_recomp_table *ctr_recomp_title_table(void) { return &table; }\n")
    path = os.path.join(outdir, "ctr_rc_table.c")
    with open(path, "w", encoding="utf-8") as out:
        out.write("".join(tab))
    files.append(path)
    summary = disc.stats()
    summary.update({
        "sha256": image.sha256,
        "image": image.as_dict(),
        "image_hash": {"lo": "0x%08X" % lo, "hi": "0x%08X" % hi, "fnv1a": "0x%08X" % h},
        "table_entries": len(entries),
        "interp_fallback_insns": fallbacks,
        "discovered_in": len(list(discovered)),
        "files": [os.path.basename(p) for p in files],
    })
    return summary


def main(argv=None):
    ap = argparse.ArgumentParser(prog="ctr_tools.recomp", description=__doc__.splitlines()[0])
    ap.add_argument("program")
    ap.add_argument("outdir")
    ap.add_argument("--discovered", help="addresses from earlier runs, one hex per line, bit 0 = Thumb")
    ap.add_argument("--report", help="also write the JSON summary to this file")
    ap.add_argument("--no-comments", action="store_true", help="no disassembly comments in the C")
    args = ap.parse_args(argv)
    try:
        image = Image.load(args.program)
    except (OSError, ThreeDsxError) as e:
        print("ctr_tools.recomp: %s: %s" % (args.program, e), file=sys.stderr)
        return 2
    summary = recompile(image, args.outdir, read_discovered(args.discovered), not args.no_comments)
    text = json.dumps(summary, sort_keys=True)
    print(text)
    if args.report:
        with open(args.report, "w", encoding="utf-8") as f:
            f.write(text + "\n")
    return 0


if __name__ == "__main__":
    sys.exit(main())
