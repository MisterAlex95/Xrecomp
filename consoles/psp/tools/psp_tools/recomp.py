"""`python3 -m psp_tools.recomp MODULE OUTDIR [--discovered FILE]`: a PSP module to C sources (XBA-224 spike).

MODULE is an EBOOT.PBP, a PRX or an ELF, loaded as consoles/psp/runtime loads it (psp_tools.prx: relocated at
0x08804000, import stubs patched). Writes OUTDIR/psp_rc_AAAAAAAA.c (the lifted functions, in files cut as
ps1_tools.recomp cuts them) and OUTDIR/psp_rc_table.c (the table, exported as psp_recomp_title_table), nothing else:
compile every .c of OUTDIR with -I consoles/psp/runtime -ffp-contract=off into one shared library
(consoles/psp/runtime/psp_recomp.h is the contract). Stale psp_rc_*.c files of an earlier run are removed. Prints a
JSON summary on stdout; --report FILE writes it there too.

Seeds: the entry (module_start), the exported functions, the R_MIPS_32 relocations that point at a plausible
function start in the code (thread entries, callbacks, function tables), and the discovered file: the addresses
psp_run --missed recorded (one hex address per line, '#' comments). Then ps1_tools' discovery.
"""

import argparse
import glob
import json
import os
import sys

from ps1_tools.discover import looks_like_start
from ps1_tools.lift import hx
from ps1_tools.recomp import chunks_of, read_discovered

from .lift import PspDiscovery, PspImage, PspLifter
from .prx import PSP_LOAD_BASE, PspError, load_file

HEADER = """/* Generated by psp_tools.recomp (consoles/psp/tools) from a PSP module -- do not edit.
 * %s sha256 %s */
#include "psp_recomp_rt.h"
"""


def build_functions(mod, discovered):
    img = PspImage(mod.code_lo, mod.code(), "exe")
    seeds = {mod.entry} | set(mod.exports.values())
    seeds |= {a for a in mod.data_ptrs if looks_like_start(img, a)}
    seeds |= {a for a, _ in discovered}
    disc = PspDiscovery(img, seeds)
    funcs = disc.run()
    return funcs, disc.stats


def fn_name(f):
    return "psp_rc_" + (f.name or "f_%08X" % f.start)


def recompile(mod, outdir, discovered=(), comments=True, resume_all=False):
    funcs, dstats = build_functions(mod, list(discovered))
    os.makedirs(outdir, exist_ok=True)
    for old in glob.glob(os.path.join(outdir, "psp_rc_*.c")):
        os.remove(old)
    names = {id(f): fn_name(f) for f in funcs}
    files, fallbacks, insns = [], 0, 0
    src = HEADER % (os.path.basename(mod.path) or mod.name, mod.sha256)
    for chunk in chunks_of(funcs):
        path = os.path.join(outdir, "psp_rc_%08X.c" % chunk[0].start)
        parts = [src]
        for f in chunk:
            lifter = PspLifter(f, names[id(f)], resume_all=resume_all)
            parts.append("\n" + lifter.function(comments))
            fallbacks += lifter.fallbacks
            insns += (f.end - f.start) // 4
        with open(path, "w", encoding="utf-8") as out:
            out.write("".join(parts))
        files.append(path)
    entries = sorted(funcs, key=lambda f: f.start)
    tab = [src, "\n"]
    for f in entries:
        tab.append("RC_FN %s(psp_machine *m_);\n" % names[id(f)])
    tab.append("\nstatic const psp_recomp_entry entries[] = {\n")
    for f in entries:
        tab.append("    {%s, %du, 0x%016XULL, %s},\n" % (hx(f.start), f.end - f.start, f.hash, names[id(f)]))
    if not entries:
        tab.append("    {0, 0, 0, 0},\n")
    tab.append("};\n\nstatic const psp_recomp_table table = {PSP_RECOMP_ABI, %du, entries, \"%s\", %s};\n\n"
               % (len(entries), mod.sha256, hx(PSP_LOAD_BASE)))
    tab.append("RC_EXPORT const psp_recomp_table *psp_recomp_title_table(void) { return &table; }\n")
    path = os.path.join(outdir, "psp_rc_table.c")
    with open(path, "w", encoding="utf-8") as out:
        out.write("".join(tab))
    files.append(path)
    vfpu = sum(1 for f in funcs for a in f.addrs if f.image.ins(a).name == "vfpu")
    return {
        "module": mod.as_dict(),
        "functions": len(funcs),
        "instructions": insns,
        "interp_fallback_insns": fallbacks,
        "vfpu_insns": vfpu,
        "discovered_in": len(list(discovered)),
        "discovery": dstats,
        "files": [os.path.basename(p) for p in files],
    }


def main(argv=None):
    ap = argparse.ArgumentParser(prog="psp_tools.recomp", description=__doc__.splitlines()[0])
    ap.add_argument("module", help="EBOOT.PBP, PRX or ELF")
    ap.add_argument("outdir")
    ap.add_argument("--discovered", help="psp_run --missed output: addresses the interpreter had to run")
    ap.add_argument("--report", help="also write the JSON summary to this file")
    ap.add_argument("--no-comments", action="store_true", help="no disassembly comments in the C")
    ap.add_argument("--resume-all", action="store_true", help="debugging: every instruction a block of its own")
    args = ap.parse_args(argv)
    try:
        mod = load_file(args.module)
    except (OSError, PspError) as e:
        print("psp_tools.recomp: %s: %s" % (args.module, e), file=sys.stderr)
        return 2
    disc = [(a, d) for a, d in read_discovered(args.discovered) if mod.code_lo <= a < mod.code_hi]
    summary = recompile(mod, args.outdir, disc, not args.no_comments, args.resume_all)
    text = json.dumps(summary, sort_keys=True)
    print(text)
    if args.report:
        with open(args.report, "w", encoding="utf-8") as f:
            f.write(text + "\n")
    return 0


if __name__ == "__main__":
    sys.exit(main())
