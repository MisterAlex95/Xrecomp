"""Generates consoles/x360/runtime/x360_interp_vmx.inc (XBA-283): the VMX / VMX128 part of the runtime's interpreter,
from the Xenon lifter itself, so interpreted vector code computes exactly what lifted code does.

    python3 -m x360_tools.gen_interp_vmx [OUT]     (default: the runtime's file; test_gen_interp_vmx checks it is current)

For every vector mnemonic of the decoder's tables (xenon.py), an instruction of that mnemonic is decoded, its
register fields are set to sentinel numbers and XenonLifter lifts it; the sentinels in the C are then renamed to the
fields the interpreter decodes at run time (vd va vb vc, rb, ra0 = (rA|0)). A field the C depends on other than as a
register number (an immediate: AltiVec's UIMM / SIMM in vA, VMX128's IMM, z, the vsldoi shift, the record bit) is
enumerated: one case per value. The dispatch mirrors XenonDecoder._op4 / _op5 / _op6 and the opcode-31 table."""

import itertools
import os
import re
import sys

from . import CONSOLE  # noqa: F401  (puts the repository root on sys.path)
from .xenon import OP5, OP6, OP6_3, OP6_R, VA4, VC4, VX4, VX128_1, X31_VMX, XenonDecoder, XenonLifter

HERE = os.path.dirname(os.path.abspath(__file__))
OUT = os.path.normpath(os.path.join(HERE, "..", "..", "runtime", "x360_interp_vmx.inc"))

VREGS = ("vd", "va", "vb", "vc")
SENT = {"vd": 121, "va": 122, "vb": 123, "vc": 124}
ALT = {"vd": 111, "va": 112, "vb": 113, "vc": 114}
RA, RB = 27, 28
RANGES = {"imm": 32, "z": 4, "sh": 16, "rc": 2}


class _F:
    entry = 0
    addrs = set()


DEC = XenonDecoder()
LIFT = XenonLifter(None, lambda a: None, _F, "gen")


def lift(word, regs, imms):
    i = DEC.decode(word, 0x82000000)
    e = i.ext
    for k, v in regs.items():
        setattr(e, k, v)
    for k, v in imms.items():
        setattr(e, k, v)
    i.ra, i.rb = RA, RB
    return i.name, LIFT.insn(i)


def rename(text, sent):
    for k, v in sent.items():
        text = text.replace("V(%d)" % v, "V(%s)" % k)
    return text.replace("R(%d)" % RA, "ra0").replace("R(%d)" % RB, "R(rb)")


def body(word, name, fields):
    """C for one mnemonic: register fields as sentinels, immediates enumerated where the C depends on them."""
    reg_set = [f for f in VREGS if f in fields]
    imms = [f for f in ("imm", "z", "sh", "rc") if f in fields]
    base = {f: 0 for f in imms}

    def gen(imm_vals, regs):
        sent = {f: SENT[f] for f in regs}
        n, t = lift(word, sent, imm_vals)
        assert n == name, (n, name)
        return rename(t, sent)

    # a register field whose number shows in the C as more than V(n) is an immediate (AltiVec's UIMM / SIMM in vA,
    # vsldoi's shift in vC)
    for f in list(reg_set):
        others = [g for g in reg_set if g != f]
        a = gen(base, reg_set)
        alt = {g: SENT[g] for g in others}
        alt[f] = ALT[f]
        n, t = lift(word, alt, base)
        if rename(t, alt) != a:
            reg_set.remove(f)
            imms.append(f)
            base[f] = 0

    def size(f):
        if f == "imm" and name == "vpermwi128":
            return 256
        return RANGES.get(f, 32)

    imm_used = []
    for f in imms:
        vals = [dict(base, **{f: v}) for v in range(size(f))]
        if len({gen(v, reg_set) for v in vals[:4] + vals[-2:]}) > 1:
            imm_used.append(f)
    if not imm_used:
        return gen(base, reg_set)
    # enumerate the immediates used (at most two: vrlimi128 / vpkd3d128 have imm and z)
    sizes = [size(f) for f in imm_used]
    shifts = [sum(s.bit_length() - 1 for s in sizes[k + 1:]) for k in range(len(sizes))]
    sel = " | ".join("(%s << %d)" % (f, sh) for f, sh in zip(imm_used, shifts))
    out = ["switch (%s) {" % sel]
    for combo in itertools.product(*[range(s) for s in sizes]):
        v = dict(base, **dict(zip(imm_used, combo)))
        key = sum(val << sh for val, sh in zip(combo, shifts))
        out.append("case %d: %s break;" % (key, gen(v, reg_set)))
    out.append("}")
    return " ".join(out)


def cases(table, opcode, fields, extra=0):
    out = []
    for key in sorted(table):
        name = table[key]
        word = (opcode << 26) | key | extra
        out.append("        case 0x%03X: /* %s */\n            %s\n            return 0;\n" % (
            key, name, body(word, name, fields)))
    return "".join(out)


def single(word, name, fields):
    return "            /* %s */\n            %s\n            return 0;\n" % (name, body(word, name, fields))


def generate():
    x31 = {k << 1: v for k, v in X31_VMX.items()}
    parts = ["/* x360_interp_vmx.inc -- generated by python3 -m x360_tools.gen_interp_vmx (XBA-283), do not edit: the\n"
             " * VMX / VMX128 instructions for x360_interp.c, lifted by XenonLifter with the fields renamed. */\n",
             "#define VMX_REGS128 (vd = ((w >> 21) & 31) | (((w >> 2) & 3) << 5), "
             "va = ((w >> 16) & 31) | (((w >> 5) & 1) << 5) | (((w >> 10) & 1) << 6), "
             "vb = ((w >> 11) & 31) | ((w & 3) << 5))\n",
             "static int vmx_exec(x360_machine *x, xe_cpu *c, uint32_t w)\n{\n"
             "    xe_machine *m_ = &x->m;\n"
             "    unsigned op = w >> 26, ra = (w >> 16) & 31, rb = (w >> 11) & 31;\n"
             "    unsigned vd = (w >> 21) & 31, va = ra, vb = rb, vc = (w >> 6) & 31, imm = 0, z = 0, sh = 0, rc = 0;\n"
             "    uint32_t ra0 = ra ? (uint32_t)c->gpr[ra] : 0;\n"
             "    (void)m_, (void)va, (void)vb, (void)vc, (void)imm, (void)z, (void)sh, (void)rc, (void)ra0;\n",
             "    if (op == 31) {\n        switch (w & 0x7FE) {\n",
             cases(x31, 31, ("vd",)),
             "        }\n        return 1;\n    }\n",
             "    if (op == 4) {\n        switch (w & 0x7F3) {\n",
             ]
    # op 4: VMX128 loads / stores first (decoder order), then VX, VC, VA, vsldoi128
    parts.append(re.sub(r"(case 0x[0-9A-F]+: /\* \S+ \*/\n)",
                        r"\1            vd = ((w >> 21) & 31) | (((w >> 2) & 3) << 5);\n", cases(VX128_1, 4, ("vd",))))
    parts.append("        default:\n            break;\n        }\n")
    parts.append("        switch (w & 0x7FF) {\n" + cases(VX4, 4, ("vd", "va", "vb")) + "        default:\n"
                 "            break;\n        }\n")
    parts.append("        rc = (w >> 10) & 1;\n        switch (w & 0x3FF) {\n" + cases(VC4, 4, ("vd", "va", "vb", "rc"))
                 + "        default:\n            break;\n        }\n")
    parts.append("        switch (w & 0x3F) {\n" + cases(VA4, 4, ("vd", "va", "vb", "vc")) + "        default:\n"
                 "            break;\n        }\n")
    parts.append("        if (w & 0x10) {\n            VMX_REGS128;\n            sh = (w >> 6) & 15;\n" +
                 single((4 << 26) | 0x10, "vsldoi128", ("vd", "va", "vb", "sh")) + "        }\n        return 1;\n"
                 "    }\n")
    parts.append("    VMX_REGS128;\n")
    parts.append("    if (op == 5) {\n        if ((w & 0x210) == 0) {\n            vc = (w >> 6) & 7;\n" +
                 single(5 << 26, "vperm128", ("vd", "va", "vb", "vc")) + "        }\n        switch (w & 0x3D0) {\n" +
                 cases(OP5, 5, ("vd", "va", "vb")) + "        default:\n            break;\n        }\n"
                 "        return 1;\n    }\n")
    parts.append("    if (op == 6) {\n        imm = (w >> 16) & 31;\n"
                 "        if ((w & 0x630) == 0x210) {\n            imm |= ((w >> 6) & 7) << 5;\n" +
                 single((6 << 26) | 0x210, "vpermwi128", ("vd", "vb", "imm")) + "        }\n"
                 "        if ((w & 0x730) == 0x610) {\n            z = (w >> 6) & 3;\n" +
                 single((6 << 26) | 0x610, "vpkd3d128", ("vd", "vb", "imm", "z")) + "        }\n"
                 "        if ((w & 0x730) == 0x710) {\n            z = (w >> 6) & 3;\n" +
                 single((6 << 26) | 0x710, "vrlimi128", ("vd", "vb", "imm", "z")) + "        }\n"
                 "        switch (w & 0x7F0) {\n" + cases(OP6_3, 6, ("vd", "vb", "imm")) + "        default:\n"
                 "            break;\n        }\n"
                 "        rc = (w >> 6) & 1;\n        switch (w & 0x390) {\n" +
                 cases(OP6_R, 6, ("vd", "va", "vb", "rc")) + "        default:\n            break;\n        }\n"
                 "        switch (w & 0x3D0) {\n" + cases(OP6, 6, ("vd", "va", "vb")) + "        default:\n"
                 "            break;\n        }\n        return 1;\n    }\n")
    parts.append("    return 1;\n}\n#undef VMX_REGS128\n")
    text = "".join(parts)
    left = re.findall(r"V\(\d+\)|R\(\d+\)", text)
    assert not left, left[:5]
    return text


def main(argv=None):
    argv = sys.argv[1:] if argv is None else argv
    out = argv[0] if argv else OUT
    text = generate()
    with open(out, "w") as f:
        f.write(text)
    print("wrote %s (%d bytes)" % (out, len(text)))
    return 0


if __name__ == "__main__":
    sys.exit(main())
