#!/usr/bin/env python3
"""gxtex's textures (XBA-262), made at build time inside the xba-gc-homebrew image: our own pictures (a hue / alpha
gradient with a checker, a 16-colour and a 256-colour picture) encoded into every GameCube texture format by
devkitPro's gxtexconv (an encoder that is not ours, so a decoder mistake cannot cancel out), then written out as C
arrays: python3 mktex.py OUTDIR  ->  OUTDIR/textures.c, OUTDIR/textures.h. Standard library only."""

import colorsys
import os
import struct
import subprocess
import sys
import zlib


def write_png(path, w, h, pixels):
    """pixels: rows of (r, g, b, a)"""
    raw = b"".join(b"\0" + b"".join(bytes(p) for p in row) for row in pixels)

    def chunk(kind, body):
        return struct.pack(">I", len(body)) + kind + body + struct.pack(">I", zlib.crc32(kind + body))

    with open(path, "wb") as f:
        f.write(b"\x89PNG\r\n\x1a\n" + chunk(b"IHDR", struct.pack(">IIBBBBB", w, h, 8, 6, 0, 0, 0))
                + chunk(b"IDAT", zlib.compress(raw, 9)) + chunk(b"IEND", b""))


def gradient(w, h):
    rows = []
    for y in range(h):
        row = []
        for x in range(w):
            r, g, b = colorsys.hsv_to_rgb(x / w, 1.0, 1.0 - 0.5 * y / h)
            c = [int(r * 255), int(g * 255), int(b * 255)]
            if ((x // 8) + (y // 8)) % 2 == 0 and y >= h // 2:
                c = [255 - v for v in c]
            a = 255 if y < h // 2 else int(255 * (h - 1 - y) / (h // 2 - 1))
            row.append((c[0], c[1], c[2], a))
        rows.append(row)
    return rows


def palette_picture(w, h, n):
    rows = []
    cols = [tuple(int(v * 255) for v in colorsys.hsv_to_rgb(i / n, 0.9, 1.0)) for i in range(n)]
    for y in range(h):
        row = []
        for x in range(w):
            i = ((x * n) // w + (y // 8)) % n
            row.append(cols[i] + (255,))
        rows.append(row)
    return rows


# name, gxtexconv colfmt, picture, palfmt
FORMATS = [
    ("i4", 0, "grad", None), ("i8", 1, "grad", None), ("ia4", 2, "grad", None), ("ia8", 3, "grad", None),
    ("rgb565", 4, "grad", None), ("rgb5a3", 5, "grad", None), ("rgba8", 6, "grad", None),
    ("ci4", 8, "pal16", 1), ("ci8", 9, "pal256", 1), ("cmpr", 14, "grad", None),
    ("mip", 4, "grad", "mip"),
]


def main():
    out = sys.argv[1]
    os.makedirs(out, exist_ok=True)
    write_png(os.path.join(out, "grad.png"), 64, 64, gradient(64, 64))
    write_png(os.path.join(out, "pal16.png"), 64, 64, palette_picture(64, 64, 16))
    write_png(os.path.join(out, "pal256.png"), 64, 64, palette_picture(64, 64, 64))
    c = ['/* generated by mktex.py: our pictures through gxtexconv */', '#include <gctypes.h>']
    h = ['/* generated by mktex.py */', '#include <gctypes.h>']
    for name, fmt, pic, pal in FORMATS:
        tpl = os.path.join(out, name + ".tpl")
        cmd = ["gxtexconv", "-i", os.path.join(out, pic + ".png"), "-o", tpl, "colfmt=%d" % fmt]
        if pal == "mip":
            cmd += ["mipmap=yes", "minlod=0", "maxlod=6"]
        elif pal is not None:
            cmd.append("palfmt=%d" % pal)
        subprocess.run(cmd, check=True, stdout=subprocess.DEVNULL)
        data = open(tpl, "rb").read()
        c.append("u8 tpl_%s[%d] __attribute__((aligned(32))) = {" % (name, len(data)))
        for i in range(0, len(data), 16):
            c.append("    " + ", ".join("0x%02x" % b for b in data[i:i + 16]) + ",")
        c.append("};")
        c.append("const u32 tpl_%s_size = %d;" % (name, len(data)))
        h.append("extern u8 tpl_%s[];" % name)
        h.append("extern const u32 tpl_%s_size;" % name)
    open(os.path.join(out, "textures.c"), "w").write("\n".join(c) + "\n")
    open(os.path.join(out, "textures.h"), "w").write("\n".join(h) + "\n")


if __name__ == "__main__":
    main()
