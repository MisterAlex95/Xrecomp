"""`python3 -m gc_tools.recomp PROG.dol OUTDIR [--discovered FILE]`: a DOL's text to C (XBA-225 spike).

Writes OUTDIR/gc_rc_NNN.c (the lifted functions, a few hundred per file so they compile in parallel) and
OUTDIR/gc_rc_table.c (the table, exported as gc_recomp_title_table), nothing else: compile every .c of OUTDIR with
-I consoles/gc/runtime into one shared library (contract: consoles/gc/runtime/gc_recomp.h).

Seeds for the discovery (tools.ppc.discover): the entry point, every aligned word of the data sections that points
into text (function pointer tables, constructors), every `lis` / `addi` (or `ori`) pair that builds a text address
(callbacks passed as arguments: interrupt handlers, thread entries), and the addresses an earlier run's interpreter
had to start at (--discovered, from gc_run --missed). The table lists every resume point of every function (its
leaders); an address that several functions hold goes to the function it starts, else to the first one.
Prints a JSON summary on stdout; --report FILE writes it there too.
"""

import argparse
import glob
import json
import os
import sys

from . import CONSOLE  # noqa: F401  (puts the repository root on sys.path for tools.ppc)
from tools.ppc.discover import Discovery
from tools.ppc.lift import hx

from .dol import DolError, Image
from .gekko import GekkoDecoder, GekkoLifter

HEADER = """/* Generated by gc_tools.recomp (consoles/gc/tools) from a GameCube DOL -- do not edit.
 * DOL sha256 %s */
#include "gc_recomp_rt.h"
"""

FUNCS_PER_FILE = 150


def fn_name(f):
    return "gc_rc_f_%08X" % f.entry


def read_discovered(path):
    out = []
    if not path or not os.path.exists(path):
        return out
    with open(path, encoding="utf-8") as f:
        for line in f:
            line = line.strip()
            if line and not line.startswith("#"):
                out.append(int(line, 16))
    return out


def code_constants(image, decoder):
    """Text addresses built by lis rX, hi ; addi / ori rY, rX, lo (within 8 instructions)."""
    found = set()
    for s in image.text:
        n = len(s.data) // 4
        for k in range(n):
            a = s.addr + 4 * k
            i = decoder.decode(image.u32(a), a)
            if i.name != "addis" or i.ra != 0:
                continue
            reg, hi = i.rd, i.uimm << 16
            for j in range(1, 9):
                b = a + 4 * j
                if not image.in_code(b):
                    break
                n2 = decoder.decode(image.u32(b), b)
                if n2.name in ("addi", "ori") and (n2.ra if n2.name == "addi" else n2.rd) == reg:
                    lo = n2.simm if n2.name == "addi" else n2.uimm
                    v = (hi + lo) & 0xFFFFFFFF
                    if v % 4 == 0 and image.in_code(v):
                        found.add(v)
                    break
                if n2.rd == reg and n2.name not in ("stw", "stb", "sth", "cmpi", "cmpli", "cmp", "cmpl"):
                    break  # register overwritten
    return found


def seeds_of(image, decoder, discovered=()):
    seeds = {image.entry}
    seeds |= {w for (_a, w) in image.data_words() if w % 4 == 0 and image.in_code(w)}
    seeds |= code_constants(image, decoder)
    seeds |= set(discovered)
    return seeds


def recompile(image, outdir, discovered=(), comments=True):
    decoder = GekkoDecoder()
    disc = Discovery(image, decoder, seeds_of(image, decoder, discovered))
    funcs = disc.run()
    os.makedirs(outdir, exist_ok=True)
    for old in glob.glob(os.path.join(outdir, "gc_rc_*.c")):
        os.remove(old)
    fallbacks = 0
    files = []
    leaders = {}
    for n in range(0, len(funcs), FUNCS_PER_FILE):
        chunk = funcs[n:n + FUNCS_PER_FILE]
        parts = [HEADER % image.sha256]
        for f in chunk:
            lifter = GekkoLifter(image, disc.insn, f, fn_name(f), comments)
            parts.append("\n" + lifter.function())
            leaders[f.entry] = lifter.leaders
            fallbacks += lifter.fallbacks
        path = os.path.join(outdir, "gc_rc_%03d.c" % (n // FUNCS_PER_FILE))
        with open(path, "w", encoding="utf-8") as out:
            out.write("".join(parts))
        files.append(path)
    # resume points -> owner
    owner = {f.entry: f for f in funcs}
    for f in funcs:
        for a in sorted(leaders[f.entry]):
            owner.setdefault(a, f)
    spans = [(s.addr, s.end, image.span_hash(s.addr, s.end)) for s in image.text]

    def span_of(a):
        for k, (lo, hi, _h) in enumerate(spans):
            if lo <= a < hi:
                return k
        raise ValueError(a)

    tab = [HEADER % image.sha256, "\n"]
    for f in funcs:
        tab.append("RC_FN %s(RC_MACHINE *m_);\n" % fn_name(f))
    tab.append("\nstatic const gc_recomp_entry entries[] = {\n")
    for a in sorted(owner):
        tab.append("    {%s, %d, %s},\n" % (hx(a), span_of(a), fn_name(owner[a])))
    if not owner:
        tab.append("    {0, 0, 0},\n")
    tab.append("};\n\nstatic const gc_recomp_span spans[] = {\n")
    for (lo, hi, h) in spans:
        tab.append("    {%s, %s, %s},\n" % (hx(lo), hx(hi), hx(h)))
    tab.append("};\n\nstatic const gc_recomp_table table = {GC_RECOMP_ABI, %du, entries, %du, spans, \"%s\"};\n\n"
               % (len(owner), len(spans), image.sha256))
    tab.append("RC_EXPORT const gc_recomp_table *gc_recomp_title_table(void) { return &table; }\n")
    path = os.path.join(outdir, "gc_rc_table.c")
    with open(path, "w", encoding="utf-8") as out:
        out.write("".join(tab))
    files.append(path)
    summary = disc.stats()
    text_insns = sum(len(s.data) // 4 for s in image.text)
    summary.update({
        "dol_sha256": image.sha256,
        "image": image.as_dict(),
        "text_instructions": text_insns,
        "seeds": len(disc.seeds),
        "spans": [{"lo": "0x%08X" % lo, "hi": "0x%08X" % hi, "fnv1a": "0x%08X" % h} for (lo, hi, h) in spans],
        "table_entries": len(owner),
        "interp_fallback_insns": fallbacks,
        "discovered_in": len(list(discovered)),
        "files": [os.path.basename(p) for p in files],
    })
    return summary


def main(argv=None):
    ap = argparse.ArgumentParser(prog="gc_tools.recomp", description=__doc__.splitlines()[0])
    ap.add_argument("dol")
    ap.add_argument("outdir")
    ap.add_argument("--discovered", help="addresses from earlier runs (gc_run --missed), one hex per line")
    ap.add_argument("--report", help="also write the JSON summary to this file")
    ap.add_argument("--no-comments", action="store_true", help="no disassembly comments in the C")
    args = ap.parse_args(argv)
    try:
        image = Image.load(args.dol)
    except (OSError, DolError) as e:
        print("gc_tools.recomp: %s: %s" % (args.dol, e), file=sys.stderr)
        return 2
    summary = recompile(image, args.outdir, read_discovered(args.discovered), not args.no_comments)
    text = json.dumps(summary, sort_keys=True)
    print(text)
    if args.report:
        with open(args.report, "w", encoding="utf-8") as f:
            f.write(text + "\n")
    return 0


if __name__ == "__main__":
    sys.exit(main())
