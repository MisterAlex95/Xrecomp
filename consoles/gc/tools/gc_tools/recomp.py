"""`python3 -m gc_tools.recomp PROG.dol OUTDIR [--discovered FILE] [--rel FILE.rel ...]`: GameCube code to C.

Writes OUTDIR/gc_rc_NNN.c (the lifted functions, a few hundred per file so they compile in parallel) and
OUTDIR/gc_rc_table.c (the table, exported as gc_recomp_title_table), nothing else: compile every .c of OUTDIR with
-I consoles/gc/runtime -ffp-contract=off -frounding-math (like gc_core: fmul then fadd round twice, and guest code
runs under the rounding mode FPSCR[RN] asks for) into one shared library (contract: consoles/gc/runtime/gc_recomp.h).

Units lifted: the DOL's text, and each REL module instance the runtime recorded (XBA-264: `REL` lines of the
discovered file, gc_tools.rel) whose module is among the --rel files: relocated here at the recorded load address and
lifted when its bytes match the run's. Each unit is discovered on its own (a REL's calls into the DOL leave through
the dispatcher), so modules loaded in turn at one address each get their functions; the table may list one address
several times, with different spans (the core runs the one whose bytes are in memory).

Seeds for the discovery (tools.ppc.discover): the entry point (a REL's prolog / epilog / unresolved), every aligned
word of the data sections that points into text (function pointer tables, constructors), every `lis` / `addi` (or
`ori`) pair that builds a text address (callbacks passed as arguments: interrupt handlers, thread entries), and the
addresses an earlier run's interpreter had to start at (--discovered, from gc_run --missed / gc_runtime's
discovered.txt). The table lists every resume point of every function (its leaders); an address that several
functions of one unit hold goes to the function it starts, else to the first one.
Prints a JSON summary on stdout; --report FILE writes it there too.
"""

import argparse
import glob
import hashlib
import json
import os
import sys

from . import CONSOLE  # noqa: F401  (puts the repository root on sys.path for tools.ppc)
from tools.ppc.discover import Discovery
from tools.ppc.lift import hx

from . import rel
from .dol import DolError, Image, Section
from .gekko import GekkoDecoder, GekkoLifter

HEADER = """/* Generated by gc_tools.recomp (consoles/gc/tools) from a GameCube DOL -- do not edit.
 * DOL sha256 %s */
#include "gc_recomp_rt.h"
"""

FUNCS_PER_FILE = 150


class RelImage:
    """A REL module as loaded (gc_tools.rel.Loaded) seen as a lifter image: its executable sections are the text, its
    other loaded sections the data (relocated: pointers to its functions are seeds)."""

    def __init__(self, loaded):
        self.loaded = loaded
        r = loaded.rel
        self.sections = []
        for k, (off, size, ex) in enumerate(r.sections):
            if not off or not size:
                continue
            self.sections.append(Section(k, "text" if ex else "data", off, loaded.addrs[k], loaded.section_bytes(k)))
        self.text = [s for s in self.sections if s.kind == "text"]
        self.entries = [a for a in loaded.entry_points() if self.in_code(a)]
        self.entry = self.entries[0] if self.entries else None
        self.sha256 = hashlib.sha256(bytes(loaded.mem)).hexdigest()

    section_at = Image.section_at
    in_code = Image.in_code
    u32 = Image.u32
    data_words = Image.data_words
    span_hash = Image.span_hash

    def as_dict(self):
        lo = self.loaded
        return {"id": lo.rel.id, "path": getattr(lo, "path", ""), "base": "0x%08X" % lo.base,
                "bss": "0x%08X" % lo.bss, "sections": [s.as_dict() for s in self.sections],
                "skipped_imports": sorted(set(lo.skipped))}


def read_discovered(path):
    """The addresses of a discovered file (one hex address per line; REL records and comments are skipped)."""
    out = []
    if not path or not os.path.exists(path):
        return out
    with open(path, encoding="utf-8", errors="replace") as f:
        for line in f:
            line = line.split("#", 1)[0].strip()
            if not line or line.startswith("REL"):
                continue
            try:
                out.append(int(line.split()[0], 16))
            except ValueError:
                continue
    return out


def read_rel_records(path):
    """The REL records of a discovered file (gc_tools.rel.parse_record), without repeats, in file order."""
    out = []
    if not path or not os.path.exists(path):
        return out
    with open(path, encoding="utf-8", errors="replace") as f:
        for line in f:
            r = rel.parse_record(line)
            if r and r not in out:
                out.append(r)
    return out


def code_constants(image, decoder):
    """Text addresses built by lis rX, hi ; addi / ori rY, rX, lo (within 8 instructions)."""
    found = set()
    for s in image.text:
        n = len(s.data) // 4
        for k in range(n):
            a = s.addr + 4 * k
            i = decoder.decode(image.u32(a), a)
            if i.name != "addis" or i.ra != 0:
                continue
            reg, hi = i.rd, i.uimm << 16
            for j in range(1, 9):
                b = a + 4 * j
                if not image.in_code(b):
                    break
                n2 = decoder.decode(image.u32(b), b)
                if n2.name in ("addi", "ori") and (n2.ra if n2.name == "addi" else n2.rd) == reg:
                    lo = n2.simm if n2.name == "addi" else n2.uimm
                    v = (hi + lo) & 0xFFFFFFFF
                    if v % 4 == 0 and image.in_code(v):
                        found.add(v)
                    break
                if n2.rd == reg and n2.name not in ("stw", "stb", "sth", "cmpi", "cmpli", "cmp", "cmpl"):
                    break  # register overwritten
    return found


def seeds_of(image, decoder, discovered=()):
    entries = getattr(image, "entries", None)
    seeds = set(entries) if entries is not None else {image.entry}
    seeds |= {w for (_a, w) in image.data_words() if w % 4 == 0 and image.in_code(w)}
    seeds |= code_constants(image, decoder)
    seeds |= {a for a in discovered if image.in_code(a)}
    return seeds


def load_rels(records, rel_files):
    """The REL instances to lift: for each record (gc_tools.rel.parse_record) whose module is among rel_files
    ({path: bytes}), the module relocated at the record's base / bss with its co-loaded modules, kept when its
    executable sections hash to the record's. Returns ([Loaded], [why a record was skipped])."""
    by_id, skipped, out = {}, [], []
    for path, raw in sorted(rel_files.items()):
        try:
            r = rel.Rel(raw)
        except rel.RelError as e:
            skipped.append("%s: %s" % (path, e))
            continue
        by_id.setdefault(r.id, (path, r))
    known = {}
    for (mid, base, bss, _h, _co) in records:
        known.setdefault((mid, base), bss)
    for (mid, base, bss, h, co) in records:
        if mid not in by_id:
            skipped.append("module %X at %08X: not among the disc's REL files" % (mid, base))
            continue
        others = []
        for (cid, cbase) in co:
            if cid in by_id and (cid, cbase) in known and cid != mid:
                others.append(rel.Loaded(by_id[cid][1], cbase, known[(cid, cbase)]))
        try:
            lo = rel.Loaded(by_id[mid][1], base, bss).link(others)
        except rel.RelError as e:
            skipped.append("module %X (%s) at %08X: %s" % (mid, by_id[mid][0], base, e))
            continue
        got = lo.exec_hash()
        if got != h:
            skipped.append("module %X (%s) at %08X: relocated bytes differ from the run's (%08X, run %08X)"
                           % (mid, by_id[mid][0], base, got, h))
            continue
        if any(lo.base == o.base and got == o.exec_hash() for o in out):
            continue
        lo.path = by_id[mid][0]
        out.append(lo)
    return out, skipped


def _lift_unit(image, decoder, discovered, prefix, comments):
    """Discovery and lift of one image: ([(fn name, C text)], {addr: fn name}, Discovery, fallbacks)."""
    disc = Discovery(image, decoder, seeds_of(image, decoder, discovered))
    funcs = disc.run()
    leaders, bodies, fallbacks = {}, [], 0

    def name(f):
        return "%s_f_%08X" % (prefix, f.entry)

    for f in funcs:
        lifter = GekkoLifter(image, disc.insn, f, name(f), comments)
        bodies.append((name(f), "\n" + lifter.function()))
        leaders[f.entry] = lifter.leaders
        fallbacks += lifter.fallbacks
    owner = {f.entry: f for f in funcs}
    for f in funcs:
        for a in sorted(leaders[f.entry]):
            owner.setdefault(a, f)
    return bodies, {a: name(f) for a, f in owner.items()}, disc, fallbacks


def recompile(image, outdir, discovered=(), comments=True, rels=()):
    """Lifts the DOL (image) and the REL instances (rels: [gc_tools.rel.Loaded]) into outdir; the JSON summary."""
    decoder = GekkoDecoder()
    discovered = list(discovered)
    os.makedirs(outdir, exist_ok=True)
    for old in glob.glob(os.path.join(outdir, "gc_rc_*.c")):
        os.remove(old)
    units = [(image, "gc_rc")] + [(RelImage(lo), "gc_rc_u%d" % (k + 1)) for k, lo in enumerate(rels)]
    files, bodies, entries, spans, stats = [], [], [], [], []
    fallbacks = 0
    for img, prefix in units:
        b, owner, disc, fb = _lift_unit(img, decoder, discovered, prefix, comments)
        fallbacks += fb
        bodies += b
        first = len(spans)
        uspans = [(s.addr, s.end, img.span_hash(s.addr, s.end)) for s in img.text]
        spans += uspans
        for a, fn in owner.items():
            k = next(k for k, (lo, hi, _h) in enumerate(uspans) if lo <= a < hi)
            entries.append((a, first + k, fn))
        st = disc.stats()
        st["seeds"] = len(disc.seeds)
        if img is not image:
            st["rel"] = img.as_dict()
        stats.append(st)
    for n in range(0, len(bodies), FUNCS_PER_FILE):
        chunk = bodies[n:n + FUNCS_PER_FILE]
        path = os.path.join(outdir, "gc_rc_%03d.c" % (n // FUNCS_PER_FILE))
        with open(path, "w", encoding="utf-8") as out:
            out.write(HEADER % image.sha256 + "".join(c for _n, c in chunk))
        files.append(path)
    entries.sort(key=lambda e: (e[0], e[1]))
    tab = [HEADER % image.sha256, "\n"]
    for fn, _c in bodies:
        tab.append("RC_FN %s(RC_MACHINE *m_);\n" % fn)
    tab.append("\nstatic const gc_recomp_entry entries[] = {\n")
    for a, sp, fn in entries:
        tab.append("    {%s, %d, %s},\n" % (hx(a), sp, fn))
    if not entries:
        tab.append("    {0, 0, 0},\n")
    tab.append("};\n\nstatic const gc_recomp_span spans[] = {\n")
    for (lo, hi, h) in spans:
        tab.append("    {%s, %s, %s},\n" % (hx(lo), hx(hi), hx(h)))
    tab.append("};\n\nstatic const gc_recomp_table table = {GC_RECOMP_ABI, %du, entries, %du, spans, \"%s\"};\n\n"
               % (len(entries), len(spans), image.sha256))
    tab.append("RC_EXPORT const gc_recomp_table *gc_recomp_title_table(void) { return &table; }\n")
    path = os.path.join(outdir, "gc_rc_table.c")
    with open(path, "w", encoding="utf-8") as out:
        out.write("".join(tab))
    files.append(path)
    summary = dict(stats[0])
    summary.update({
        "dol_sha256": image.sha256,
        "image": image.as_dict(),
        "text_instructions": sum(len(s.data) // 4 for s in image.text),
        "spans": [{"lo": "0x%08X" % lo, "hi": "0x%08X" % hi, "fnv1a": "0x%08X" % h} for (lo, hi, h) in spans],
        "table_entries": len(entries),
        "interp_fallback_insns": fallbacks,
        "discovered_in": len(discovered),
        "rels": stats[1:],
        "files": [os.path.basename(p) for p in files],
    })
    return summary


def main(argv=None):
    ap = argparse.ArgumentParser(prog="gc_tools.recomp", description=__doc__.splitlines()[0])
    ap.add_argument("dol")
    ap.add_argument("outdir")
    ap.add_argument("--discovered", help="addresses and REL records from earlier runs (gc_runtime discovered.txt)")
    ap.add_argument("--rel", action="append", default=[], help="a REL module of the disc (repeatable)")
    ap.add_argument("--report", help="also write the JSON summary to this file")
    ap.add_argument("--no-comments", action="store_true", help="no disassembly comments in the C")
    args = ap.parse_args(argv)
    try:
        image = Image.load(args.dol)
    except (OSError, DolError) as e:
        print("gc_tools.recomp: %s: %s" % (args.dol, e), file=sys.stderr)
        return 2
    files = {}
    for p in args.rel:
        with open(p, "rb") as f:
            files[os.path.basename(p)] = f.read()
    rels, skipped = load_rels(read_rel_records(args.discovered), files)
    summary = recompile(image, args.outdir, read_discovered(args.discovered), not args.no_comments, rels)
    summary["rel_skipped"] = skipped
    text = json.dumps(summary, sort_keys=True)
    print(text)
    if args.report:
        with open(args.report, "w", encoding="utf-8") as f:
            f.write(text + "\n")
    return 0


if __name__ == "__main__":
    sys.exit(main())
