"""`python3 -m nds_tools.recomp ROM.nds OUTDIR [--discovered FILE]`: a DS program's ARM9 code to C (XBA-223 spike).

Writes OUTDIR/nds_rc_AAAAAAAA{a,t}.c (the lifted functions, files cut as gba_tools.recomp cuts them) and
OUTDIR/nds_rc_table.c (the table, exported as nds_recomp_title_table), nothing else: compile every .c of OUTDIR with
-I consoles/nds/runtime into one shared library (contract: consoles/nds/runtime/nds_recomp.h).

The table also lists the code spans: per run-time segment, the bytes from its first to its last lifted instruction
with their FNV-1a hash. DS code lives in RAM, and the boot stub runs where .main lands later: the core runs a span's
functions only once its bytes in memory match (nds_recomp.c).
Prints a JSON summary on stdout; --report FILE writes it there too.
"""

import argparse
import glob
import json
import os
import sys

from . import CONSOLE  # noqa: F401  (puts gba_tools on sys.path)
from gba_tools.discover import islands
from gba_tools.lift import hx
from gba_tools.recomp import chunks_of, read_discovered

from .lift import NdsDiscovery, NdsLifter
from .nds import Image, NdsError

HEADER = """/* Generated by nds_tools.recomp (consoles/nds/tools) from a DS program -- do not edit.
 * ROM sha256 %s */
#include "nds_recomp_rt.h"
"""


def fn_name(f):
    return "nds_rc_f_%08X_%s" % (f.entry, "t" if f.thumb else "a")


def spans_of(image, funcs):
    """[(lo, hi, hash)]: per segment, first to last lifted byte."""
    out = []
    for s in image.segments:
        lo, hi = None, None
        for f in funcs:
            size = 2 if f.thumb else 4
            fl, fh = min(f.addrs), max(f.addrs) + size
            if s.vma <= fl < s.end:
                lo = fl if lo is None else min(lo, fl)
                hi = fh if hi is None else max(hi, fh)
        if lo is not None:
            hi = min(hi, s.end)
            out.append((lo, hi, image.span_hash(lo, hi)))
    return out


def recompile(image, outdir, discovered=(), comments=True):
    disc = NdsDiscovery(image, discovered)
    funcs = disc.run()
    os.makedirs(outdir, exist_ok=True)
    for old in glob.glob(os.path.join(outdir, "nds_rc_*.c")):
        os.remove(old)
    fallbacks = 0
    files = []
    for chunk in chunks_of(funcs):
        path = os.path.join(outdir, "nds_rc_%08X%s.c" % (chunk[0].entry, "t" if chunk[0].thumb else "a"))
        parts = [HEADER % image.sha256]
        for f in chunk:
            lifter = NdsLifter(image, f.thumb, f.addrs)
            text = lifter.function(fn_name(f), (f.entry >> 24) & 15, comments)
            parts.append("\n" + text.replace("(gba_machine *m_)", "(nds_machine *m_)", 1))
            fallbacks += lifter.fallbacks
        with open(path, "w", encoding="utf-8") as out:
            out.write("".join(parts))
        files.append(path)
    entries = islands(funcs)
    spans = spans_of(image, funcs)
    tab = [HEADER % image.sha256, "\n"]
    for f in funcs:
        tab.append("RC_FN %s(nds_machine *m_);\n" % fn_name(f))
    tab.append("\nstatic const nds_recomp_entry entries[] = {\n")
    for (addr, thumb, f) in entries:
        tab.append("    {%s, %d, %s},\n" % (hx(addr), 1 if thumb else 0, fn_name(f)))
    if not entries:
        tab.append("    {0, 0, 0},\n")
    tab.append("};\n\nstatic const nds_recomp_span spans[] = {\n")
    for (lo, hi, h) in spans:
        tab.append("    {%s, %s, %s},\n" % (hx(lo), hx(hi), hx(h)))
    if not spans:
        tab.append("    {0, 0, 0},\n")
    tab.append("};\n\nstatic const nds_recomp_table table = {NDS_RECOMP_ABI, %du, entries, %du, spans, \"%s\"};\n\n"
               % (len(entries), len(spans), image.sha256))
    tab.append("RC_EXPORT const nds_recomp_table *nds_recomp_title_table(void) { return &table; }\n")
    path = os.path.join(outdir, "nds_rc_table.c")
    with open(path, "w", encoding="utf-8") as out:
        out.write("".join(tab))
    files.append(path)
    summary = disc.stats()
    summary.update({
        "rom_sha256": image.sha256,
        "header": image.header.as_dict(),
        "image": image.as_dict(),
        "spans": [{"lo": "0x%08X" % lo, "hi": "0x%08X" % hi, "fnv1a": "0x%08X" % h} for (lo, hi, h) in spans],
        "table_entries": len(entries),
        "interp_fallback_insns": fallbacks,
        "discovered_in": len(list(discovered)),
        "files": [os.path.basename(p) for p in files],
    })
    return summary


def main(argv=None):
    ap = argparse.ArgumentParser(prog="nds_tools.recomp", description=__doc__.splitlines()[0])
    ap.add_argument("rom")
    ap.add_argument("outdir")
    ap.add_argument("--discovered", help="addresses from earlier runs, one hex per line, bit 0 = Thumb")
    ap.add_argument("--report", help="also write the JSON summary to this file")
    ap.add_argument("--no-comments", action="store_true", help="no disassembly comments in the C")
    args = ap.parse_args(argv)
    try:
        image = Image.load(args.rom)
    except (OSError, NdsError) as e:
        print("nds_tools.recomp: %s: %s" % (args.rom, e), file=sys.stderr)
        return 2
    summary = recompile(image, args.outdir, read_discovered(args.discovered), not args.no_comments)
    text = json.dumps(summary, sort_keys=True)
    print(text)
    if args.report:
        with open(args.report, "w", encoding="utf-8") as f:
            f.write(text + "\n")
    return 0


if __name__ == "__main__":
    sys.exit(main())
