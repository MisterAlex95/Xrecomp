"""`python3 -m ps2_tools.recomp ELF OUTDIR [--discovered FILE]`: a PS2 EE executable to C sources (XBA-226 spike).

ELF is loaded as consoles/ps2/runtime loads it (ps2_tools.elf). Writes OUTDIR/ps2_rc_AAAAAAAA.c (the lifted
functions, in files cut as ps1_tools.recomp cuts them) and OUTDIR/ps2_rc_table.c (the table, exported as
ps2_recomp_title_table), nothing else: compile every .c of OUTDIR with -I consoles/ps2/runtime -ffp-contract=off into
one shared library (consoles/ps2/runtime/ps2_recomp.h is the contract). Stale ps2_rc_*.c files of an earlier run are
removed. Prints a JSON summary on stdout; --report FILE writes it there too.

Seeds: the entry, the words of the loaded image (code and data: function tables, constructors, callbacks) that
point at a plausible function start in the code, and the discovered file: the addresses ps2_run --missed recorded
(one hex address per line, '#' comments). Then ps1_tools' discovery. The ELF's symbol table is not used: a disc's
executable has none.
"""

import argparse
import glob
import json
import os
import sys

from ps1_tools.discover import looks_like_start
from ps1_tools.lift import hx
from ps1_tools.recomp import chunks_of, read_discovered

from .elf import Ps2Error, load_file
from .lift import Ps2Discovery, Ps2Image, Ps2Lifter

HEADER = """/* Generated by ps2_tools.recomp (consoles/ps2/tools) from a PS2 EE executable -- do not edit.
 * %s sha256 %s */
#include "ps2_recomp_rt.h"
"""


def build_functions(exe, discovered):
    img = Ps2Image(exe.code_lo, exe.code(), "exe")
    seeds = {exe.entry}
    seeds |= {v for _, v in exe.words() if img.contains(v) and looks_like_start(img, v)}
    seeds |= {a for a, _ in discovered}
    disc = Ps2Discovery(img, seeds)
    funcs = disc.run()
    return funcs, disc.stats


def fn_name(f):
    return "ps2_rc_" + (f.name or "f_%08X" % f.start)


def recompile(exe, outdir, discovered=(), comments=True, resume_all=False):
    funcs, dstats = build_functions(exe, list(discovered))
    os.makedirs(outdir, exist_ok=True)
    for old in glob.glob(os.path.join(outdir, "ps2_rc_*.c")):
        os.remove(old)
    names = {id(f): fn_name(f) for f in funcs}
    files, fallbacks, insns = [], 0, 0
    src = HEADER % (os.path.basename(exe.path), exe.sha256)
    for chunk in chunks_of(funcs):
        path = os.path.join(outdir, "ps2_rc_%08X.c" % chunk[0].start)
        parts = [src]
        for f in chunk:
            lifter = Ps2Lifter(f, names[id(f)], resume_all=resume_all)
            parts.append("\n" + lifter.function(comments))
            fallbacks += lifter.fallbacks
            insns += (f.end - f.start) // 4
        with open(path, "w", encoding="utf-8") as out:
            out.write("".join(parts))
        files.append(path)
    entries = sorted(funcs, key=lambda f: f.start)
    tab = [src, "\n"]
    for f in entries:
        tab.append("RC_FN %s(ps2_machine *m_);\n" % names[id(f)])
    tab.append("\nstatic const ps2_recomp_entry entries[] = {\n")
    for f in entries:
        tab.append("    {%s, %du, 0x%016XULL, %s},\n" % (hx(f.start), f.end - f.start, f.hash, names[id(f)]))
    if not entries:
        tab.append("    {0, 0, 0, 0},\n")
    tab.append("};\n\nstatic const ps2_recomp_table table = {PS2_RECOMP_ABI, %du, entries, \"%s\"};\n\n"
               % (len(entries), exe.sha256))
    tab.append("RC_EXPORT const ps2_recomp_table *ps2_recomp_title_table(void) { return &table; }\n")
    path = os.path.join(outdir, "ps2_rc_table.c")
    with open(path, "w", encoding="utf-8") as out:
        out.write("".join(tab))
    files.append(path)
    kinds = {}
    for f in funcs:
        for a in f.addrs:
            i = f.image.ins(a)
            if i.cls == "mmi" or (i.cls == "interp" and (i.name.startswith("mmi") or i.name == "cop2")):
                kinds[i.name] = kinds.get(i.name, 0) + 1
    return {
        "elf": exe.as_dict(),
        "functions": len(funcs),
        "instructions": insns,
        "interp_fallback_insns": fallbacks,
        "mmi_and_cop2": dict(sorted(kinds.items())),
        "discovered_in": len(list(discovered)),
        "discovery": dstats,
        "files": [os.path.basename(p) for p in files],
    }


def main(argv=None):
    ap = argparse.ArgumentParser(prog="ps2_tools.recomp", description=__doc__.splitlines()[0])
    ap.add_argument("elf", help="the EE executable (ELF)")
    ap.add_argument("outdir")
    ap.add_argument("--discovered", help="ps2_run --missed output: addresses the interpreter had to run")
    ap.add_argument("--report", help="also write the JSON summary to this file")
    ap.add_argument("--no-comments", action="store_true", help="no disassembly comments in the C")
    ap.add_argument("--resume-all", action="store_true", help="debugging: every instruction a block of its own")
    args = ap.parse_args(argv)
    try:
        exe = load_file(args.elf)
    except (OSError, Ps2Error) as e:
        print("ps2_tools.recomp: %s: %s" % (args.elf, e), file=sys.stderr)
        return 2
    disc = [(a, d) for a, d in read_discovered(args.discovered) if exe.code_lo <= a < exe.code_hi]
    summary = recompile(exe, args.outdir, disc, not args.no_comments, args.resume_all)
    text = json.dumps(summary, sort_keys=True)
    print(text)
    if args.report:
        with open(args.report, "w", encoding="utf-8") as f:
            f.write(text + "\n")
    return 0


if __name__ == "__main__":
    sys.exit(main())
